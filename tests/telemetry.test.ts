import {test} from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {randomUUID} from 'node:crypto';
import {createApp} from '../server/app.js';
import {database} from '../server/db.js';

test('host activity reports current/backward steps, waiting, save problems, freshness; stage stays aggregate-only',async()=>{
  const dir=await mkdtemp(join(tmpdir(),'bwt-activity-'));
  const db=await database(undefined,join(dir,'database'));
  const app=await createApp({db,dataDir:dir,adminToken:'test-admin',origins:['http://localhost:5173']});
  const call=async(method:any,url:string,token='',payload?:any)=>{const r=await app.inject({method,url,headers:token?{authorization:'Bearer '+token}:{},payload});return {status:r.statusCode,data:r.json()};};
  try{
    const {id,code,hostToken,stageToken}=(await call('POST','/v1/sessions','test-admin',{title:'Activity test',flowVersion:2})).data;
    const root='/v1/sessions/'+id;
    const user=(await call('POST','/v1/join','',{code,joinKey:randomUUID()})).data;
    const foreign=(await call('POST','/v1/sessions','test-admin',{title:'Other session',flowVersion:2})).data;
    const report={step:1,visibility:'visible',pendingSaves:0,syncStatus:'saved',waitingForPhase:1,photos:{pile:true,build:false,concept:false},handedOff:false,cardReady:false};
    assert.equal((await call('POST',root+'/telemetry',hostToken,report)).status,401);
    assert.equal((await call('POST',root+'/telemetry',stageToken,report)).status,401);
    assert.equal((await call('POST','/v1/sessions/'+foreign.id+'/telemetry',user.token,report)).status,401);
    assert.equal((await call('POST',root+'/telemetry',user.token,{...report,step:10})).status,400);
    assert.equal((await call('POST',root+'/telemetry',user.token,{...report,privateNote:'Must stay on the phone'})).status,400);
    await call('PATCH',root+'/control',hostToken,{expectedRevision:0,phase:0});
    assert.equal((await call('POST',root+'/telemetry',user.token,report)).status,200);
    const me=(await call('GET',root,user.token)).data.participant;
    assert.equal(me.revision,0,'activity must not invalidate in-flight survey writes');
    assert.equal(me.data.progress,0,'activity must not overwrite saved progress');
    let host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.telemetry.steps[1],1);assert.equal(host.telemetry.waiting,1);assert.equal(host.telemetry.recent,1);
    assert.equal(host.telemetry.participants[0].photos.pile,true);
    const stage=(await call('GET',root+'/snapshot',stageToken)).data;
    assert.equal('telemetry' in stage,false);assert.equal(JSON.stringify(stage).includes(user.participant.id),false);
    await call('PATCH',root+'/control',hostToken,{expectedRevision:1,phase:4});
    await call('PATCH',root+'/me',user.token,{operationId:randomUUID(),expectedRevision:0,patch:{progress:5,before:1}});
    await call('POST',root+'/telemetry',user.token,{...report,step:2,waitingForPhase:null,pendingSaves:2,syncStatus:'queued'});
    host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.progress[5],1);assert.equal(host.telemetry.steps[2],1,'back navigation must show the actual current screen');
    assert.equal(host.telemetry.waiting,0);assert.equal(host.telemetry.needsAttention,0,'a normal short upload queue is not a problem');
    const old=new Date(Date.now()-120000).toISOString();
    await db.query('UPDATE participants SET step_started_at=$1,pending_since_at=$1 WHERE id=$2',[old,user.participant.id]);
    await call('POST',root+'/telemetry',user.token,{...report,step:2,waitingForPhase:null,pendingSaves:2,syncStatus:'queued'});
    host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.telemetry.participants[0].stepStartedAt,old,'heartbeat must preserve time on screen');
    assert.equal(host.telemetry.needsAttention,1,'long pending saves need attention');
    await call('POST',root+'/telemetry',user.token,{...report,step:4,waitingForPhase:null});
    host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.telemetry.needsAttention,0);assert.equal(host.telemetry.participants[0].pendingSince,null);
    assert.ok(Date.parse(host.telemetry.participants[0].stepStartedAt)>Date.parse(old));
    await db.query("UPDATE participants SET step_started_at=now()-interval '10 minutes' WHERE id=$1",[user.participant.id]);
    assert.equal((await call('GET',root+'/snapshot',hostToken)).data.telemetry.needsAttention,0,'a long build alone is not an error');
    await call('POST',root+'/telemetry',user.token,{...report,step:4,syncStatus:'error',pendingSaves:1,visibility:'hidden',waitingForPhase:null});
    host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.telemetry.needsAttention,1);assert.equal(host.telemetry.participants[0].visibility,'hidden');
    await db.query("UPDATE participants SET telemetry_at=now()-interval '3 minutes',last_seen_at=now()-interval '3 minutes' WHERE id=$1",[user.participant.id]);
    host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.telemetry.recent,0);assert.equal(host.telemetry.needsAttention,0,'stale reports must not imply a current live error');
    await db.query("UPDATE participants SET current_step=NULL,telemetry_at=NULL,client_status='{}',step_started_at=NULL WHERE id=$1",[user.participant.id]);
    host=(await call('GET',root+'/snapshot',hostToken)).data;
    assert.equal(host.telemetry.participants[0].reported,false);assert.equal(host.telemetry.steps[5],1,'older clients retain last-saved progress');
  }finally{await app.close();await rm(dir,{recursive:true,force:true});}
});
